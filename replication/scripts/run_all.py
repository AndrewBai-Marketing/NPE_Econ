def _conjugate_evidence_path(results_dir: Path, allow_recorded: bool) -> tuple[Path, str]:
    fresh = results_dir / "conjugate_normal" / "validation_metrics.json"
    if fresh.is_file():
        return fresh, "fresh replication run"
    if allow_recorded:
        recorded = ROOT / "validation" / "exact_example" / "output" / "validation_metrics.json"
        if recorded.is_file():
            return recorded, "committed release evidence"
    raise FileNotFoundError("No conjugate validation metrics are available for the SBC stage.")


def _run_sbc(results_dir: Path, config: dict[str, Any], allow_recorded: bool) -> dict[str, Any]:
    started_at = utc_now()
    started = time.perf_counter()
    path, origin = _conjugate_evidence_path(results_dir, allow_recorded)
    payload = load_json(path)
    sbc = payload["sbc"]
    configuration = sbc["configuration"]
    regions = sbc["by_parameter_and_region"]
    histogram = sbc["rank_histogram"]
    conditions = [
        configuration["cases"] == config["cases"],
        configuration["posterior_draws_per_case"] == config["posterior_draws_per_case"],
        configuration["rank_histogram_bins"] == config["rank_histogram_bins"],
        [row["region"] for row in regions] == config["regions"],
        sum(histogram["counts"]) == config["cases"],
        config["acceptance"]["gating"] is False,
    ]
    if not all(conditions):
        raise RuntimeError("SBC output does not match the frozen 32-case descriptive configuration.")
    all_region = regions[0]
    return {
        "name": "sbc_32",
        "status": "PASS",
        "started_at": started_at,
        "finished_at": utc_now(),
        "duration_seconds": time.perf_counter() - started,
        "command": None,
        "evidence": repository_relative(path),
        "evidence_origin": origin,
        "gating": False,
        "interpretation": config["acceptance"]["reason"],
        "summary": {
            key: all_region[key]
            for key in ("n", "bias", "rmse", "coverage_50", "coverage_80", "coverage_90", "coverage_95", "mean_rank_fraction")
        },
    }


