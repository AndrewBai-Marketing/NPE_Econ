def _planned_stage(name: str) -> dict[str, Any]:
    return {
        "name": name,
        "status": "PLANNED",
        "description": STAGE_DESCRIPTIONS[name],
        "command": "See the frozen JSON config and run_all.py stage definition.",
    }


def _failed_stage(name: str, error: Exception) -> dict[str, Any]:
    return {
        "name": name,
        "status": "FAIL",
        "started_at": utc_now(),
        "finished_at": utc_now(),
        "duration_seconds": 0.0,
        "error": f"{type(error).__name__}: {error}",
    }


def _load_evidence(results_dir: Path, allow_recorded: bool) -> dict[str, dict[str, Any]]:
    evidence: dict[str, dict[str, Any]] = {}
    candidates = {
        "conjugate_normal": results_dir / "conjugate_normal" / "validation_metrics.json",
        "structural_grid": results_dir / "structural_grid" / "validation_metrics.json",
        "benchmark": results_dir / "benchmark" / "benchmark_results.json",
    }
    recorded = {
        "conjugate_normal": ROOT / "validation" / "exact_example" / "output" / "validation_metrics.json",
        "structural_grid": ROOT / "validation" / "structural_example" / "output" / "validation_metrics.json",
        "benchmark": ROOT / "benchmarks" / "benchmark_results.json",
    }
    for name, path in candidates.items():
        if path.is_file():
            evidence[name] = load_json(path)
        elif allow_recorded and recorded[name].is_file():
            evidence[name] = load_json(recorded[name])
    return evidence


def _summary_status(stages: list[dict[str, Any]], comparisons: list[dict[str, Any]], dry_run: bool) -> str:
    if dry_run:
        return "PLANNED"
    if any(stage["status"] in {"FAIL", "BLOCKED"} for stage in stages):
        return "FAIL"
    if any(item["gating"] and item["passed"] is False for item in comparisons):
        return "FAIL"
    return "PASS"


def main() -> int:
    args = parse_args()
    config_audit = validate_replication_configs()
    results_dir = _resolve(args.results_dir)
    report_path = _resolve(args.report) if args.report is not None else results_dir / "report.json"
    selected = _csv(args.only) if args.only else set(STAGE_ORDER)
    skipped = _csv(args.skip)
    unknown = (selected | skipped) - set(STAGE_ORDER)
    if unknown:
        raise ValueError(f"Unknown stage ID(s): {', '.join(sorted(unknown))}")
    skipped &= selected
    active = selected - skipped
    started_at = utc_now()

    pipeline = load_json(CONFIGS / "pipeline_smoke.json")
    exact = load_json(CONFIGS / "conjugate_normal_smoke.json")
    sbc = load_json(CONFIGS / "sbc_32.json")
    structural = load_json(CONFIGS / "structural_grid_smoke.json")
    benchmark = load_json(CONFIGS / "cpu_benchmark.json")
    expected = load_json(EXPECTED)

    base_report: dict[str, Any] = {
        "schema_version": 1,
        "release": "0.1.0b1",
        "profile": args.profile,
        "started_at": started_at,
        "config_audit": config_audit,
        "selection": {
            "selected": [name for name in STAGE_ORDER if name in selected],
            "skipped": [name for name in STAGE_ORDER if name in skipped],
            "use_recorded_evidence": bool(args.use_recorded_evidence),
        },
        "machine": machine_metadata(),
        "version_control": git_metadata(),
        "stages": [],
        "comparisons": [],
    }

    if args.profile == "full":
        full = load_json(CONFIGS / "full_profile.json")
        stages = []
        for name in STAGE_ORDER:
            status = "SKIPPED" if name in skipped else ("UNRUN_FUTURE_WORK" if name in selected else "NOT_SELECTED")
            stages.append(
                {
                    "name": name,
                    "status": status,
                    "description": STAGE_DESCRIPTIONS[name],
                    "reason": full["execution_policy"] if status == "UNRUN_FUTURE_WORK" else None,
                }
            )
        report = {
            **base_report,
            "status": "UNRUN_FUTURE_WORK",
            "finished_at": utc_now(),
            "full_profile": full,
            "stages": stages,
            "summary": {
                "claim": "No full-profile result is claimed for 0.1.0b1.",
                "selected_unrun": sum(stage["status"] == "UNRUN_FUTURE_WORK" for stage in stages),
            },
        }
        write_json(report_path, report)
        print(json.dumps({"status": "UNRUN_FUTURE_WORK", "report": repository_relative(report_path)}, indent=2))
        return 0

    if args.dry_run:
        stages = []
        for name in STAGE_ORDER:
            if name in skipped:
                stages.append({"name": name, "status": "SKIPPED", "description": STAGE_DESCRIPTIONS[name]})
            elif name in selected:
                stages.append(_planned_stage(name))
            else:
                stages.append({"name": name, "status": "NOT_SELECTED", "description": STAGE_DESCRIPTIONS[name]})
        report = {
            **base_report,
            "status": "PLANNED",
            "finished_at": utc_now(),
            "stages": stages,
            "summary": {"planned": sum(stage["status"] == "PLANNED" for stage in stages)},
        }
        write_json(report_path, report)
        print(json.dumps({"status": "PLANNED", "report": repository_relative(report_path)}, indent=2))
        return 0

    runners: dict[str, Callable[[], dict[str, Any]]] = {
        "package_tests": lambda: _run_package_tests(results_dir, pipeline),
        "build_distributions": lambda: _run_build(results_dir, pipeline),
        "wheel_install": lambda: _run_install(results_dir, pipeline, "wheel"),
        "sdist_install": lambda: _run_install(results_dir, pipeline, "sdist"),
        "conjugate_normal": lambda: _run_conjugate(results_dir, exact),
        "sbc_32": lambda: _run_sbc(results_dir, sbc, args.use_recorded_evidence),
        "structural_grid": lambda: _run_structural(results_dir, structural),
        "support_warning": lambda: _run_support(results_dir, pipeline),
        "save_reload": lambda: _run_save_reload(results_dir, pipeline),
        "cpu_neural": lambda: _run_cpu_neural(results_dir, pipeline),
        "benchmark": lambda: _run_benchmark(results_dir, benchmark),
    }

    stages: list[dict[str, Any]] = []
    for name in STAGE_ORDER:
        if name not in selected:
            stages.append({"name": name, "status": "NOT_SELECTED", "description": STAGE_DESCRIPTIONS[name]})
            continue
        if name in skipped:
            stages.append({"name": name, "status": "SKIPPED", "description": STAGE_DESCRIPTIONS[name]})
            continue
        try:
            result = runners[name]()
        except Exception as error:  # retain a complete multi-stage report
            result = _failed_stage(name, error)
        result.setdefault("description", STAGE_DESCRIPTIONS[name])
        stages.append(result)
        partial = {**base_report, "status": "RUNNING", "stages": stages, "finished_at": None}
        write_json(report_path, partial)

    evidence = _load_evidence(results_dir, args.use_recorded_evidence)
    comparisons = compare_expected(expected, evidence, active)
    status = _summary_status(stages, comparisons, dry_run=False)
    counts = {state: sum(stage["status"] == state for stage in stages) for state in ("PASS", "FAIL", "SKIPPED", "NOT_SELECTED")}
    report = {
        **base_report,
        "status": status,
        "finished_at": utc_now(),
        "stages": stages,
        "comparisons": comparisons,
        "summary": {
            "stage_counts": counts,
            "gating_comparisons_passed": sum(item["gating"] and item["passed"] is True for item in comparisons),
            "gating_comparisons_failed": sum(item["gating"] and item["passed"] is False for item in comparisons),
            "descriptive_comparisons": sum(not item["gating"] for item in comparisons),
            "timing_is_gating": False,
            "scientific_scope": "Release-pipeline evidence only; no claim of general structural accuracy, identification, or specification validity.",
        },
    }
    write_json(report_path, report)
    print(json.dumps({"status": status, "report": repository_relative(report_path)}, indent=2))
    return 0 if status == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
