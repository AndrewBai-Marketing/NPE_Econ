def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", choices=("smoke", "full"), default="smoke")
    parser.add_argument(
        "--only",
        help="Comma-separated stage IDs to run. Omit to select every smoke stage.",
    )
    parser.add_argument(
        "--skip",
        default="",
        help="Comma-separated selected stage IDs to mark SKIPPED.",
    )
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=Path("replication/results/smoke"),
        help="Generated artifacts and logs (relative paths resolve from repository root).",
    )
    parser.add_argument(
        "--report",
        type=Path,
        default=None,
        help="Machine-readable report path; defaults to RESULTS_DIR/report.json.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Validate configs and write a PLANNED report without running subprocesses.",
    )
    parser.add_argument(
        "--use-recorded-evidence",
        action="store_true",
        help="Allow comparison-only stages to use committed 0.1.0b1 output when fresh output is absent.",
    )
    return parser.parse_args()


def _csv(value: str | None) -> set[str]:
    if not value:
        return set()
    return {item.strip() for item in value.split(",") if item.strip()}


def _resolve(path: Path) -> Path:
    return path if path.is_absolute() else ROOT / path


def _command_stage(
    *,
    name: str,
    command: list[str],
    display: list[str],
    results_dir: Path,
    timeout: int,
    extra_environment: dict[str, str] | None = None,
) -> dict[str, Any]:
    environment = replication_environment()
    environment.update(extra_environment or {})
    return run_command(
        name=name,
        command=command,
        display_command=display,
        log_dir=results_dir / "logs",
        timeout_seconds=timeout,
        environment=environment,
    )


def _artifact_details(paths: list[Path]) -> list[dict[str, Any]]:
    return [
        {
            "path": repository_relative(path),
            "bytes": path.stat().st_size,
            "sha256": sha256_file(path),
        }
        for path in paths
        if path.is_file()
    ]


def _find_distribution(results_dir: Path, kind: str) -> Path:
    distribution = results_dir / "distributions"
    pattern = "structnpe-0.1.0b1-*.whl" if kind == "wheel" else "structnpe-0.1.0b1.tar.gz"
    candidates = sorted(distribution.glob(pattern))
    if not candidates:
        raise FileNotFoundError(
            f"No {kind} found under {repository_relative(distribution)}; run build_distributions first."
        )
    return candidates[-1]


def _run_package_tests(results_dir: Path, pipeline: dict[str, Any]) -> dict[str, Any]:
    timeout = pipeline["stages"]["package_tests"]["timeout_seconds"]
    return _command_stage(
        name="package_tests",
        command=[sys.executable, "-m", "pytest", "-q"],
        display=["python", "-m", "pytest", "-q"],
        results_dir=results_dir,
        timeout=timeout,
    )


def _run_build(results_dir: Path, pipeline: dict[str, Any]) -> dict[str, Any]:
    output = results_dir / "distributions"
    output.mkdir(parents=True, exist_ok=True)
    timeout = pipeline["stages"]["build_distributions"]["timeout_seconds"]
    result = _command_stage(
        name="build_distributions",
        command=[sys.executable, "-m", "build", "--outdir", str(output)],
        display=["python", "-m", "build", "--outdir", repository_relative(output)],
        results_dir=results_dir,
        timeout=timeout,
    )
    if result["status"] == "PASS":
        artifacts = sorted(output.glob("structnpe-0.1.0b1*"))
        if not any(path.suffix == ".whl" for path in artifacts) or not any(path.name.endswith(".tar.gz") for path in artifacts):
            result["status"] = "FAIL"
            result["error"] = "Build returned success without both 0.1.0b1 distribution formats."
        else:
            sdist = next(path for path in artifacts if path.name.endswith(".tar.gz"))
            normalization = _command_stage(
                name="normalize_sdist",
                command=[
                    sys.executable,
                    str(ROOT / "scripts" / "normalize_sdist.py"),
                    str(sdist),
                ],
                display=[
                    "python",
                    "scripts/normalize_sdist.py",
                    repository_relative(sdist),
                ],
                results_dir=results_dir,
                timeout=60,
            )
            result["sdist_normalization"] = normalization
            if normalization["status"] != "PASS":
                result["status"] = "FAIL"
                result["error"] = "Public sdist metadata normalization failed."
            else:
                distribution_audit = _command_stage(
                    name="distribution_boundary",
                    command=[
                        sys.executable,
                        "-m",
                        "pytest",
                        "-q",
                        str(ROOT / "tests" / "test_structnpe_distribution_contents.py"),
                    ],
                    display=[
                        "python",
                        "-m",
                        "pytest",
                        "-q",
                        "tests/test_structnpe_distribution_contents.py",
                    ],
                    results_dir=results_dir,
                    timeout=120,
                    extra_environment={"STRUCTNPE_DIST_DIR": str(output)},
                )
                result["distribution_boundary"] = distribution_audit
                if distribution_audit["status"] != "PASS":
                    result["status"] = "FAIL"
                    result["error"] = "Built distribution boundary audit failed."
        result["artifacts"] = _artifact_details(artifacts)
    return result


def _run_install(results_dir: Path, pipeline: dict[str, Any], kind: str) -> dict[str, Any]:
    stage = f"{kind}_install"
    artifact = _find_distribution(results_dir, kind)
    output = results_dir / "install_checks" / f"{stage}.json"
    timeout = pipeline["stages"][stage]["timeout_seconds"]
    result = _command_stage(
        name=stage,
        command=[
            sys.executable,
            str(ROOT / "replication" / "scripts" / "install_check.py"),
            "--artifact",
            str(artifact),
            "--kind",
            kind,
            "--output",
            str(output),
        ],
        display=[
            "python",
            "replication/scripts/install_check.py",
            "--artifact",
            repository_relative(artifact),
            "--kind",
            kind,
            "--output",
            repository_relative(output),
        ],
        results_dir=results_dir,
        timeout=timeout,
    )
    if output.is_file():
        result["result"] = repository_relative(output)
    return result


